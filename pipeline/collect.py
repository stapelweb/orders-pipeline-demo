# -*- coding: utf-8 -*-
"""Сбор заявок из внешнего источника: забрать, привести к виду, схлопнуть дубли.

Что здесь показано нарочно, потому что именно на этом ломаются интеграции:

1. ИСТОЧНИК ОТВЕЧАЕТ НЕ ТОЛЬКО 200. Есть 429 (слишком часто), 403, 5xx и
   обрыв. Поэтому запрос с повторами и нарастающей паузой, а не один вызов
   в надежде на лучшее.
2. HTML-СУЩНОСТИ. Поле с суммой может прийти как `1&nbsp;500&#8381;`.
   Без `html.unescape` сумма не разбирается вовсе, и это видно не сразу:
   запись просто молча получает ноль.
3. ТЕЛЕФОН — КЛЮЧ, А НЕ УКРАШЕНИЕ. Пока он не приведён к одному виду,
   дубли не схлопываются: `8 (912) 345-67-89` и `+7 912 345 67 89` для
   программы разные люди.
4. ИДЕМПОТЕНТНОСТЬ. Повторный прогон на тех же данных не должен менять
   результат. Проверяется тестом, а не обещанием.

Запуск без сети, на вложенных данных:
    python -m pipeline collect

С живого адреса:
    python -m pipeline collect --url https://example.com/api/orders
"""

from __future__ import annotations

import html
import json
import logging
import re
import sqlite3
import time
import urllib.error
import urllib.request
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Iterable

КОРЕНЬ = Path(__file__).resolve().parent.parent
БАЗА = КОРЕНЬ / "data" / "orders.db"
ФИКСТУРА = КОРЕНЬ / "fixtures" / "orders.json"

ПОВТОРЫ = 4
ПАУЗА_БАЗОВАЯ = 1.5  # секунды; дальше удваивается

журнал = logging.getLogger("collect")


# --------------------------------------------------------------------------
#  Приведение полей
# --------------------------------------------------------------------------

def нормализовать_телефон(сырой: Any) -> str | None:
    """К виду +7XXXXXXXXXX. None — если к одиннадцати цифрам не приводится.

    Догадок не делаем: семёрку дописываем только десятизначному номеру,
    начинающемуся с девятки, — там результат однозначен.
    """
    цифры = re.sub(r"\D+", "", str(сырой or ""))
    if not цифры:
        return None
    if len(цифры) == 11 and цифры[0] in "78":
        return "+7" + цифры[1:]
    if len(цифры) == 10 and цифры[0] == "9":
        return "+7" + цифры
    return None


def разобрать_сумму(сырое: Any) -> int:
    """Сумма из строки любого вида, включая HTML-сущности и неразрывные пробелы.

    `1&nbsp;500&#8381;` → 1500. Без unescape сюда приходит ноль, и ошибку
    видно только по итоговым цифрам, что дорого.
    """
    if isinstance(сырое, (int, float)):
        return int(сырое)
    текст = html.unescape(str(сырое or ""))
    цифры = re.sub(r"[^\d]", "", текст)
    return int(цифры) if цифры else 0


def разобрать_время(сырое: Any) -> str:
    """ISO-время в UTC. Непонятное время — момент разбора, но об этом в журнал.

    Молча подставлять «сейчас» нельзя: по этому полю потом считают давность.
    """
    текст = str(сырое or "").strip()
    for образец in ("%Y-%m-%dT%H:%M:%S%z", "%Y-%m-%dT%H:%M:%S", "%Y-%m-%d %H:%M:%S", "%Y-%m-%d"):
        try:
            м = datetime.strptime(текст, образец)
            if м.tzinfo is None:
                м = м.replace(tzinfo=timezone.utc)
            return м.astimezone(timezone.utc).isoformat()
        except ValueError:
            continue
    журнал.warning("время не разобрано: %r — ставлю текущее", сырое)
    return datetime.now(timezone.utc).isoformat()


def привести(запись: dict) -> dict | None:
    """Сырая запись источника → наша. None — если без телефона, то есть без ключа."""
    телефон = нормализовать_телефон(запись.get("phone") or запись.get("телефон"))
    if телефон is None:
        журнал.info("пропуск: телефон не приводится — %r", запись.get("phone"))
        return None
    return {
        "телефон": телефон,
        "имя": html.unescape(str(запись.get("name") or запись.get("имя") or "")).strip(),
        "сумма": разобрать_сумму(запись.get("amount") or запись.get("сумма")),
        "создана": разобрать_время(запись.get("created_at") or запись.get("создана")),
        "источник": str(запись.get("source") or "fixture"),
    }


def схлопнуть(записи: Iterable[dict]) -> list[dict]:
    """Дубли по телефону: оставляем запись с большей суммой, при равенстве — позднюю.

    Правило выбрано так, а не «последняя побеждает», потому что повторная
    заявка часто приходит укороченной, без суммы: взяв её вслепую, мы бы
    обнулили то, что уже знали.
    """
    лучшие: dict[str, dict] = {}
    for з in записи:
        т = з["телефон"]
        прежняя = лучшие.get(т)
        if прежняя is None:
            лучшие[т] = з
            continue
        если_дороже = з["сумма"] > прежняя["сумма"]
        если_ровно_и_позже = з["сумма"] == прежняя["сумма"] and з["создана"] > прежняя["создана"]
        if если_дороже or если_ровно_и_позже:
            лучшие[т] = з
    # Порядок фиксируем, иначе ответ «плавает» между прогонами.
    return sorted(лучшие.values(), key=lambda з: з["телефон"])


# --------------------------------------------------------------------------
#  Источник
# --------------------------------------------------------------------------

def забрать(url: str | None) -> list[dict]:
    """Данные из сети или из вложенной фикстуры, если адрес не задан."""
    if not url:
        журнал.info("источник: вложенная фикстура %s", ФИКСТУРА.name)
        return json.loads(ФИКСТУРА.read_text(encoding="utf-8"))

    пауза = ПАУЗА_БАЗОВАЯ
    последняя_ошибка: Exception | None = None
    for попытка in range(1, ПОВТОРЫ + 1):
        try:
            запрос = urllib.request.Request(url, headers={"User-Agent": "pipeline-demo/1.0"})
            with urllib.request.urlopen(запрос, timeout=15) as ответ:
                тело = ответ.read().decode("utf-8", "replace")
            данные = json.loads(тело)
            return данные if isinstance(данные, list) else данные.get("items", [])
        except urllib.error.HTTPError as e:
            последняя_ошибка = e
            # 429 и 5xx имеет смысл повторить, 4xx кроме 429 — нет.
            if e.code != 429 and e.code < 500:
                журнал.error("источник отказал: HTTP %s — повторять бессмысленно", e.code)
                raise
            журнал.warning("HTTP %s, попытка %s из %s, пауза %.1f с", e.code, попытка, ПОВТОРЫ, пауза)
        except (urllib.error.URLError, TimeoutError, json.JSONDecodeError) as e:
            последняя_ошибка = e
            журнал.warning("%s, попытка %s из %s, пауза %.1f с", type(e).__name__, попытка, ПОВТОРЫ, пауза)
        time.sleep(пауза)
        пауза *= 2
    raise RuntimeError(f"источник недоступен после {ПОВТОРЫ} попыток: {последняя_ошибка}")


# --------------------------------------------------------------------------
#  Хранилище
# --------------------------------------------------------------------------

СХЕМА = """
CREATE TABLE IF NOT EXISTS orders (
    телефон   TEXT PRIMARY KEY,
    имя       TEXT NOT NULL,
    сумма     INTEGER NOT NULL,
    создана   TEXT NOT NULL,
    источник  TEXT NOT NULL,
    увидена   TEXT NOT NULL,
    обновлена TEXT NOT NULL
)
"""


def открыть(путь: Path = БАЗА) -> sqlite3.Connection:
    путь.parent.mkdir(parents=True, exist_ok=True)
    соединение = sqlite3.connect(путь)
    соединение.execute(СХЕМА)
    return соединение


def сохранить(соединение: sqlite3.Connection, записи: list[dict]) -> dict[str, int]:
    """Вставка-обновление. Возвращает счёт: новых, обновлённых, без изменений.

    `увидена` при обновлении НЕ трогаем — это момент первой встречи, по нему
    считают, сколько запись у нас живёт.
    """
    сейчас = datetime.now(timezone.utc).isoformat()
    счёт = {"новых": 0, "обновлено": 0, "без изменений": 0}
    for з in записи:
        строка = соединение.execute(
            "SELECT имя, сумма, создана, источник FROM orders WHERE телефон = ?", (з["телефон"],)
        ).fetchone()
        if строка is None:
            соединение.execute(
                "INSERT INTO orders (телефон, имя, сумма, создана, источник, увидена, обновлена)"
                " VALUES (?,?,?,?,?,?,?)",
                (з["телефон"], з["имя"], з["сумма"], з["создана"], з["источник"], сейчас, сейчас),
            )
            счёт["новых"] += 1
        elif tuple(строка) != (з["имя"], з["сумма"], з["создана"], з["источник"]):
            соединение.execute(
                "UPDATE orders SET имя=?, сумма=?, создана=?, источник=?, обновлена=? WHERE телефон=?",
                (з["имя"], з["сумма"], з["создана"], з["источник"], сейчас, з["телефон"]),
            )
            счёт["обновлено"] += 1
        else:
            счёт["без изменений"] += 1
    соединение.commit()
    return счёт


def прогон(url: str | None = None, путь: Path = БАЗА) -> dict[str, int]:
    """Полный проход: забрать → привести → схлопнуть → сохранить."""
    сырые = забрать(url)
    приведённые = [п for п in (привести(з) for з in сырые) if п is not None]
    готовые = схлопнуть(приведённые)
    журнал.info(
        "получено %s, приведено %s, после схлопывания %s",
        len(сырые), len(приведённые), len(готовые),
    )
    соединение = открыть(путь)
    try:
        return сохранить(соединение, готовые)
    finally:
        соединение.close()
