# -*- coding: utf-8 -*-
"""Проверки конвейера. Запуск: python tests/test_pipeline.py

Тесты написаны не для галочки: каждый закрывает ошибку, которая в живых
интеграциях стоила времени. Поэтому рядом с проверкой стоит, что именно
она ловит.
"""

from __future__ import annotations

import json
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from pipeline import collect, report  # noqa: E402

провалов = 0


def проверить(условие: bool, что: str) -> None:
    global провалов
    if условие:
        print(f"  ok   {что}")
    else:
        провалов += 1
        print(f"  ПЛОХО {что}")


print("ТЕЛЕФОН — приведение к одному виду")
проверить(collect.нормализовать_телефон("8 (912) 345-67-89") == "+79123456789",
          "восьмёрка и скобки")
проверить(collect.нормализовать_телефон("+7 912 345 67 89") == "+79123456789",
          "семёрка и пробелы дают тот же ключ")
проверить(collect.нормализовать_телефон("9123456789") == "+79123456789",
          "десять цифр с девятки")
проверить(collect.нормализовать_телефон("уточнить") is None,
          "текст вместо номера — не выдумываем, отдаём None")
проверить(collect.нормализовать_телефон("12345") is None,
          "короткий номер отвергается, а не дополняется")

print()
print("СУММА — HTML-сущности и неразрывные пробелы")
проверить(collect.разобрать_сумму("12&nbsp;000&#8381;") == 12000,
          "неразрывный пробел и знак рубля сущностью")
проверить(collect.разобрать_сумму("7 500") == 7500, "обычный пробел")
проверить(collect.разобрать_сумму("") == 0, "пустое — ноль, а не ошибка")
проверить(collect.разобрать_сумму(48000) == 48000, "число приходит числом")

print()
print("СХЛОПЫВАНИЕ ДУБЛЕЙ")
записи = [
    {"телефон": "+79123456789", "имя": "А", "сумма": 12000, "создана": "2026-10-14T09:12:00+00:00", "источник": "сайт"},
    {"телефон": "+79123456789", "имя": "А", "сумма": 12000, "создана": "2026-10-14T11:40:00+00:00", "источник": "бот"},
    {"телефон": "+79261234567", "имя": "С", "сумма": 48000, "создана": "2026-10-15T08:03:00+00:00", "источник": "сайт"},
    {"телефон": "+79261234567", "имя": "С", "сумма": 0,     "создана": "2026-10-16T19:21:00+00:00", "источник": "бот"},
]
итог = collect.схлопнуть(записи)
проверить(len(итог) == 2, "четыре записи сворачиваются в двух человек")
по_телефону = {з["телефон"]: з for з in итог}
проверить(по_телефону["+79261234567"]["сумма"] == 48000,
          "поздняя пустая заявка НЕ затирает известную сумму")
проверить(по_телефону["+79123456789"]["источник"] == "бот",
          "при равных суммах побеждает поздняя")
проверить([з["телефон"] for з in итог] == sorted(з["телефон"] for з in итог),
          "порядок зафиксирован — ответ не плавает между прогонами")

print()
print("ХРАНИЛИЩЕ — идемпотентность")
with tempfile.TemporaryDirectory() as каталог:
    путь = Path(каталог) / "test.db"
    первый = collect.прогон(None, путь)
    второй = collect.прогон(None, путь)
    проверить(первый["новых"] > 0, f"первый прогон что-то записал ({первый['новых']})")
    проверить(второй["новых"] == 0, "повторный прогон НЕ создаёт дублей")
    проверить(второй["обновлено"] == 0, "и ничего не переписывает без причины")

    экран = report.собрать(путь, Path(каталог) / "d.html")
    текст = экран.read_text(encoding="utf-8")
    проверить("<table" in текст, "экран собрался и содержит таблицу")
    проверить("prefers-color-scheme" in текст, "тёмная тема на месте")
    проверить(len(текст) > 2000, "страница не пустая")

print()
print("ФИКСТУРА — данные для демонстрации на месте")
данные = json.loads((Path(__file__).resolve().parent.parent / "fixtures" / "orders.json").read_text(encoding="utf-8"))
проверить(len(данные) >= 8, "в фикстуре есть что схлопывать")
проверить(any("уточнить" in str(з.get("phone", "")) for з in данные),
          "есть запись без телефона — проверяем, что её отбрасывают")

print()
if провалов:
    print(f"ПРОВАЛОВ: {провалов}")
    sys.exit(1)
print("все проверки пройдены")
